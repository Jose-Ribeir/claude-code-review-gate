# Scenario C. Every required section is present, but Decision precedes
# Context -- the unconditional wait-what rule. The decision ruling carries
# the distinctive quote the assertion looks for.
_ADR_0102 = """# ADR-0102: The disconnect path flushes pending events through the queue

## Status

Accepted

## Decision

On disconnect, the app flushes all pending events through the pool manager
queue before the window closes, and no renderer ever writes the queue file
directly. This record exists so a later change cannot reopen a direct
writer path without an explicit new decision.

## Context

Bug reports from the field show events lost when a remote session drops.
Today each caller glues its own flush logic, and the shutdown order varies
per entry point, which makes the lost-event reports hard to reproduce.

## Consequences

Flush logic moves into the pool manager disconnect handler. Callers stop
carrying their own copies of the flush-and-close sequence.
"""

# Scenario D. packages/shared/src/utils/gitStatus.ts exists at the tip, but
# it has no `stagedPaths` helper (its status helpers are untrackedPaths and
# MAX_UNTRACKED_PATHS) -- the existence evidence stays silent and the
# integrity duty must read the file to disprove the claim.
_ADR_0103 = """# ADR-0103: Stage-panel filtering goes through stagedPaths

## Status

Accepted

## Context

The status panel needs the paths of entries with a staged change so it can
render the staged column. The shared package keeps the status helpers.

## Decision

The panel reads staged entries through the stagedPaths helper in
packages/shared/src/utils/gitStatus.ts, which returns the paths of
entries whose index values mark a staged change.

## Consequences

Any change to how staged entries are identified happens in that helper.
"""

# Scenario E. Seeded ADR-0001 says explicitly that a transcript file "is
# never rewritten in place after its first save". This record claims the
# opposite and builds its decision on the misquote.
_ADR_0104 = """# ADR-0104: Reuse the transcript format for autosave snapshots

## Status

Accepted

## Context

ADR 0001 recorded that session transcripts are rewritten in place on every
save. Autosave snapshots can therefore follow the same write path as
transcripts.

## Decision

Autosave snapshots reuse the session transcript files described in ADR
0001 and are rewritten in place on every save.

## Consequences

No new snapshot directory is needed.
"""

# Scenario F. The Decision states present facts about an external hosted
# service (retention window, response code, latency bound) that cannot be
# verified from the tip's code or docs -- guilty-until-proven-innocent
# (SPEC-14.6) blocks.
_ADR_0105 = """# ADR-0105: Session archives trust the archive service retention

## Status

Accepted

## Context

The desktop app uploads finished session archives to the hosted archive
service so a device swap can recover them.

## Decision

The archive service at archive.kimchi.dev holds every uploaded session for
exactly 90 days and confirms each upload with an HTTP 201 response within
300 ms, so the app needs neither a retry loop nor a local retention sweep.

## Consequences

No local expiry code ships in this change.
"""

# Scenario G. Every claim is verifiable at the tip: `untrackedPaths` and
# `MAX_UNTRACKED_PATHS` exist in the named file and do exactly what is
# claimed (index and working status both '?'; cap of 5000), and the
# ADR-0001 citation matches the seeded record word for word in substance.
# Context precedes Decision; sentences are short; no slop.
_ADR_0106 = """# ADR-0106: The status panel caps its untracked list through shared helpers

## Status

Accepted

## Context

The status panel lists untracked paths so users see new files before
staging them. The shared package already exposes the status helpers the
renderer uses.

## Decision

The panel builds its untracked list with the untrackedPaths helper in
packages/shared/src/utils/gitStatus.ts. That helper returns the
repo-relative paths of entries whose index and working-tree status are
both a question mark. The untracked list is capped at 5000 entries per
request by MAX_UNTRACKED_PATHS in the same file. ADR 0001 already records
that session transcripts persist as append-only files in the workspace
state directory and are never rewritten in place, and nothing in this
record changes that.

## Consequences

The renderer never batches more than 5000 untracked entries per request.
"""

