_SEED_ADR_0001 = """# ADR-0001: Session transcripts persist as append-only files

## Status

Accepted

## Context

The desktop app keeps a transcript of every session so a later session can
resume it and the history view can list past runs. Early prototypes kept
the transcript in renderer memory only, which lost the record on any
window reload.

## Decision

Session transcripts persist as append-only files in the workspace state
directory. Each session writes its own transcript file, and a transcript
file is never rewritten in place after its first save.

## Consequences

Crash recovery reads the last transcript from disk instead of asking the
renderer for it. Rotation is not part of this record.
"""

