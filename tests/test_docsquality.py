def _run_cli(args, stdin=""):
    script = os.path.join(_SCRIPTS, "ocr_docsquality.py")
    proc = subprocess.run([sys.executable, script] + args, input=stdin,
                          capture_output=True, text=True, timeout=60)
    assert proc.returncode == 0, proc.stderr  # fail-soft: never crash the gate
    return proc


class TestCLI:
    def test_evidence_mode_round_trip(self, scratch):
        proc = _run_cli(["--repo-root", scratch, "docs/guide.md"])
        out = json.loads(proc.stdout)
        assert set(out) == {"evidence", "warnings"}
        assert out["evidence"]["docs/guide.md"]["dangling_links"] == [
            {"path": "docs/missing.md", "line": 3, "kind": "markdown_link"}]

    def test_evidence_mode_sentence_cap_flag(self, scratch):
        proc = _run_cli(["--repo-root", scratch, "--sentence-cap", "5",
                         "docs/ste.md"])
        over = json.loads(proc.stdout)["evidence"]["docs/ste.md"]["ste"]
        assert over["sentence_length"]["cap"] == 5
        assert over["sentence_length"]["over_cap"][-1] == {"line": 2, "words": 26}

    def test_validate_mode_round_trip(self):
        f = _finding(tells=[_tell(12), _tell(15), _tell(18)])
        proc = _run_cli(["--validate"], stdin=json.dumps([f]))
        out = json.loads(proc.stdout)
        assert out["findings"] == [f]
        assert out["demoted"] == 0

    def test_validate_mode_demotes(self):
        f = _finding(tells=[_tell(12)])
        proc = _run_cli(["--validate"], stdin=json.dumps([f]))
        got = json.loads(proc.stdout)["findings"][0]
        assert got["severity"] == "note" and got["demoted"] is True

    def test_validate_mode_garbage_stdin_exits_zero(self):
        out = json.loads(_run_cli(["--validate"], stdin="junk").stdout)
        assert out["findings"] == [] and out["warnings"]

    def test_validate_mode_empty_stdin_exits_zero(self):
        out = json.loads(_run_cli(["--validate"], stdin="").stdout)
        assert out["findings"] == [] and out["warnings"]

    def test_dump_schema_to_stdout(self):
        out = json.loads(_run_cli(["--dump-schema"]).stdout)
        assert out == dq.DOCQUALITY_SCHEMA


