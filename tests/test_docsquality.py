def _finding(**over):
    f = {"path": "docs/sloppy.md", "start_line": 10, "end_line": 20,
         "severity": "high", "confidence": 0.9, "content": "reads like slop"}
    f.update(over)
    return f


def _tell(line=None, phrase="delve"):
    t = {"phrase": phrase}
    if line is not None:
        t["line"] = line
    return t


class TestClusterRule:
    def test_one_tell_demotes(self):
        f = _finding(tells=[_tell(12)])
        out = dq.validate_findings([f])
        assert out["demoted"] == 1
        got = out["findings"][0]
        assert got["severity"] == "note"
        assert got["demoted"] is True
        assert "1" in got["demotion_reason"] and "high" in got["demotion_reason"]
        assert got["tells"] == f["tells"]  # tells preserved verbatim

    def test_two_tells_demotes(self):
        f = _finding(tells=[_tell(12), _tell(15)])
        out = dq.validate_findings([f])
        assert out["demoted"] == 1
        assert out["findings"][0]["severity"] == "note"

    def test_missing_tells_key_demotes(self):
        out = dq.validate_findings([_finding()])
        assert out["demoted"] == 1
        assert out["findings"][0]["severity"] == "note"

    def test_three_co_located_tells_pass_untouched(self):
        f = _finding(tells=[_tell(12), _tell(15), _tell(18)])
        out = dq.validate_findings([f])
        assert out["demoted"] == 0
        assert out["findings"][0] == f  # every field untouched

    def test_tells_outside_finding_span_do_not_count(self):
        """Of three tells, one beyond end_line: only two co-located -> demote."""
        f = _finding(tells=[_tell(12), _tell(15), _tell(30)])
        out = dq.validate_findings([f])
        assert out["demoted"] == 1
        assert out["findings"][0]["demoted"] is True

    def test_unlined_tells_never_count(self):
        """The contract is (phrase + line): a tell without a line cannot be
        placed inside the span either, so it never counts toward co-location
        -- three line-less tells must not dodge the cluster rule."""
        f = _finding(tells=[_tell(), _tell(), _tell()])
        out = dq.validate_findings([f])
        assert out["demoted"] == 1
        assert out["findings"][0]["severity"] == "note"
        assert "0" in out["findings"][0]["demotion_reason"]

    def test_unlined_tells_add_nothing_to_a_cluster(self):
        """Two in-span tells plus any number of unlined ones: still two
        co-located, so the finding demotes."""
        f = _finding(tells=[_tell(12), _tell(15), _tell(), _tell()])
        out = dq.validate_findings([f])
        assert out["demoted"] == 1
        assert out["findings"][0]["severity"] == "note"

    def test_unlined_extra_tells_do_not_unseat_a_real_cluster(self):
        """Three in-span tells pass untouched; unlined extras are ignored,
        not subtracted."""
        tells = [_tell(12), _tell(15), _tell(18), _tell(), _tell()]
        f = _finding(tells=tells)
        out = dq.validate_findings([f])
        assert out["demoted"] == 0
        assert out["findings"][0] == f

    def test_finding_without_line_bounds_has_no_co_location(self):
        """A finding without numeric line bounds can never satisfy
        co-location -- lined tells included; only document_wide saves it."""
        f = _finding(tells=[_tell(1), _tell(50), _tell(90)])
        del f["start_line"], f["end_line"]
        out = dq.validate_findings([f])
        assert out["demoted"] == 1
        assert out["findings"][0]["severity"] == "note"

    def test_document_wide_bypasses_cluster_rule(self):
        for n_tells in (0, 1, 2):
            f = _finding(document_wide=True, tells=[_tell(12)] * n_tells)
            out = dq.validate_findings([f])
            assert out["demoted"] == 0
            assert out["findings"][0] == f
            assert "demoted" not in out["findings"][0]

    def test_extra_fields_preserved_on_demotion(self):
        f = _finding(tells=[_tell(12)], extra={"a": [1, 2]}, flag=None, n=7)
        out = dq.validate_findings([f])
        got = out["findings"][0]
        assert got["extra"] == {"a": [1, 2]}
        assert got["flag"] is None
        assert got["n"] == 7
        assert got["confidence"] == 0.9
        assert got["content"] == "reads like slop"

    def test_note_severity_finding_still_demoted(self):
        """The rule is mechanical: the demotion marks the finding, regardless
        of the severity it already carried."""
        f = _finding(severity="note", tells=[_tell(12)])
        out = dq.validate_findings([f])
        assert out["findings"][0]["demoted"] is True
        assert out["demoted"] == 1

    def test_mixed_array_and_demoted_count(self):
        findings = [
            _finding(tells=[_tell(12)]),
            _finding(tells=[_tell(12), _tell(15), _tell(18)]),
            _finding(document_wide=True, tells=[]),
        ]
        out = dq.validate_findings(findings)
        assert out["demoted"] == 1
        assert len(out["findings"]) == 3
        assert out["findings"][1] == findings[1]
        assert out["findings"][2] == findings[2]

    def test_object_with_findings_array_accepted(self):
        f = _finding(tells=[_tell(12), _tell(15), _tell(18)])
        out = dq.validate_findings(json.dumps({"findings": [f]}))
        assert out["findings"] == [f]
        assert out["demoted"] == 0

    def test_non_dict_entries_pass_through(self):
        out = dq.validate_findings(json.dumps(["junk", 42]))
        assert out["findings"] == ["junk", 42]
        assert out["demoted"] == 0

    def test_input_objects_not_mutated(self):
        f = _finding(tells=[_tell(12)])
        snapshot = json.loads(json.dumps(f))
        dq.validate_findings([f])
        assert f == snapshot


