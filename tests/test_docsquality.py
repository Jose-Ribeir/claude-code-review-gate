"""Tests for scripts/ocr_docsquality.py — deterministic docs-quality evidence
and the deslop finding-contract (cluster rule) validator (SPEC-14.2).

Evidence mode computes existence facts (missing referenced paths, unresolved
ADR refs, dangling doc links), a deslop pre-pass (catalog hits, em-dash count,
template skeletons, throat-clearing openers) and STE surface stats (sentence
length outliers, acronym first-use table, passive-voice estimate) against a
scratch repo whose docs carry hand-computed expected output. Validate mode
demotes any finding without document_wide: true whose tells array holds fewer
than 3 co-located entries to note severity, preserving every other field.
Both modes are fail-soft and never raise, whatever the input.
"""
