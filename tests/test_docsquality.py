_SCHEMA_PATH = os.path.join(_REPO, "schemas", "docsquality.schema.json")


class TestSchema:
    def test_checked_in_schema_equals_generated(self):
        with open(_SCHEMA_PATH, encoding="utf-8") as fh:
            checked_in = json.load(fh)
        assert checked_in == dq.DOCQUALITY_SCHEMA

    def test_schema_describes_evidence_envelope(self):
        schema = dq.DOCQUALITY_SCHEMA
        assert schema["type"] == "object"
        assert set(schema["required"]) == {"evidence", "warnings"}
        per_file = schema["properties"]["evidence"]["additionalProperties"]
        assert set(per_file["required"]) == {
            "missing_paths", "unresolved_adr_refs", "dangling_links",
            "deslop", "ste"}

    def test_evidence_output_matches_schema_shape(self, scratch):
        """Structural agreement: every fixture file's evidence validates
        against the schema's required-key discipline."""
        out = _evidence(scratch, "docs/guide.md", "docs/adr-note.md",
                        "docs/sloppy.md", "docs/ste.md", "docs/template.md")
        per_file = dq.DOCQUALITY_SCHEMA["properties"]["evidence"]["additionalProperties"]
        required = set(per_file["required"])
        for rel, ev in out["evidence"].items():
            assert required <= set(ev), rel
            deslop_req = per_file["properties"]["deslop"]["required"]
            assert set(deslop_req) <= set(ev["deslop"]), rel
            ste_req = per_file["properties"]["ste"]["required"]
            assert set(ste_req) <= set(ev["ste"]), rel
